import { execFile } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { awgConfFile, HUB_MANAGEMENT_IP, networkSubnet } from './config.js';
import { isValidKey } from './util.js';

const AWG = process.env.NUROFEN_AWG_BIN || 'awg';
const AWG_QUICK = process.env.NUROFEN_AWG_QUICK_BIN || 'awg-quick';
const IPTABLES = process.env.NUROFEN_IPTABLES_BIN || 'iptables';

export function exec(cmd, args, options = {}) {
  return new Promise((resolve, reject) => {
    execFile(cmd, args, { timeout: 20000, windowsHide: true, ...options }, (error, stdout, stderr) => {
      if (error) {
        error.stdout = String(stdout || '');
        error.stderr = String(stderr || '');
        reject(error);
        return;
      }
      resolve(String(stdout || ''));
    });
  });
}

async function which(bin) {
  try {
    const out = await exec(process.platform === 'win32' ? 'where' : 'which', [bin]);
    return out.trim().split(/\r?\n/)[0] || null;
  } catch {
    return null;
  }
}

export async function awgStatus(cfg) {
  const hasAwg = Boolean(await which(AWG));
  const hasQuick = Boolean(await which(AWG_QUICK));
  let up = false;
  if (hasAwg) {
    try {
      await exec(AWG, ['show', cfg.server.interface]);
      up = true;
    } catch {
      up = false;
    }
  }
  return { hasAwg, hasQuick, up, dryRun: !hasAwg || !hasQuick };
}

/**
 * Full interface configuration. Only used when the interface is created or
 * when obfuscation parameters change (both require a restart).
 */
export function renderServerConfig(cfg) {
  const o = cfg.awg.obfuscation;
  // One Address per network: the hub is 10.66.<n>.1 in every network it hosts.
  const addresses = cfg.networks.map((network) => {
    const net = networkSubnet(network);
    return `Address = ${net.serverIp}/${net.prefix}`;
  });
  if (!addresses.length) addresses.push(`Address = ${HUB_MANAGEMENT_IP}/32`);

  const lines = [
    '# Generated by Nurofen. Do not edit by hand: the control plane owns this file.',
    '[Interface]',
    `PrivateKey = ${cfg.awg.privateKey}`,
    ...addresses,
    `ListenPort = ${cfg.server.awgPort}`,
    `MTU = ${cfg.server.mtu}`,
    `Jc = ${o.Jc}`,
    `Jmin = ${o.Jmin}`,
    `Jmax = ${o.Jmax}`,
    `S1 = ${o.S1}`,
    `S2 = ${o.S2}`,
    `H1 = ${o.H1}`,
    `H2 = ${o.H2}`,
    `H3 = ${o.H3}`,
    `H4 = ${o.H4}`,
  ];

  const peers = cfg.peers.filter((peer) => !peer.revoked && isValidKey(peer.publicKey));
  if (peers.length === 0) {
    lines.push('', '# No peers yet.');
  }
  for (const peer of peers) {
    lines.push(
      '',
      `# ${sanitizeComment(peer.name)}`,
      '[Peer]',
      `PublicKey = ${peer.publicKey}`,
      `AllowedIPs = ${peer.ip}/32`,
    );
  }
  return `${lines.join('\n')}\n`;
}

function sanitizeComment(value) {
  return String(value || 'peer').replace(/[\r\n=#]/g, ' ').slice(0, 48);
}

/**
 * Client configuration, also used by the "download .conf" button so people can
 * feed the file to the stock AmneziaWG client if they prefer.
 */
export function renderClientConfig(cfg, peer, privateKey, port = cfg.server.awgPort) {
  const network = cfg.networks.find((item) => item.id === peer.networkId);
  const net = networkSubnet(network);
  const o = cfg.awg.obfuscation;
  const lines = [
    '# Nurofen profile',
    '[Interface]',
    `PrivateKey = ${privateKey}`,
    // /24 (not /32) so that the whole subnet is treated as on-link inside the tunnel.
    `Address = ${peer.ip}/${net.prefix}`,
    `MTU = ${cfg.server.mtu}`,
    `Jc = ${o.Jc}`,
    `Jmin = ${o.Jmin}`,
    `Jmax = ${o.Jmax}`,
    `S1 = ${o.S1}`,
    `S2 = ${o.S2}`,
    `H1 = ${o.H1}`,
    `H2 = ${o.H2}`,
    `H3 = ${o.H3}`,
    `H4 = ${o.H4}`,
    '',
    '[Peer]',
    `PublicKey = ${cfg.awg.publicKey}`,
    `Endpoint = ${cfg.server.publicHost}:${port}`,
    // Only this network: the client never gets routes into other people's nets.
    `AllowedIPs = ${net.cidr}`,
    `PersistentKeepalive = ${cfg.server.keepalive}`,
  ];
  return `${lines.join('\n')}\n`;
}

export async function applyServer(cfg, log = console) {
  const confPath = awgConfFile(cfg);
  const conf = renderServerConfig(cfg);
  fs.mkdirSync(path.dirname(confPath), { recursive: true, mode: 0o700 });
  fs.writeFileSync(confPath, conf, { mode: 0o600 });

  const status = await awgStatus(cfg);
  if (status.dryRun) {
    log.warn?.('[awg] amneziawg-tools not found, running in dry-run mode (config written only)');
    return { ...status, applied: false };
  }

  if (!status.up) {
    await exec(AWG_QUICK, ['up', confPath]);
    log.info?.(`[awg] interface ${cfg.server.interface} is up`);
    await applyIsolation(cfg, log);
    return { ...status, up: true, applied: true };
  }

  await syncAddresses(cfg, log);
  await syncPeers(cfg, log);
  await applyIsolation(cfg, log);
  return { ...status, applied: true };
}

/**
 * A new network adds a hub address to the live interface without a restart:
 * `ip addr add 10.66.<n>.1/24 dev nurofen0`. Deleting a network removes it.
 */
export async function syncAddresses(cfg, log = console) {
  if (process.platform === 'win32') return { synced: false, reason: 'unsupported-platform' };
  const status = await awgStatus(cfg);
  if (status.dryRun || !status.up) return { synced: false, reason: 'interface-down' };

  const iface = cfg.server.interface;
  const desired = new Set(cfg.networks.map((network) => {
    const net = networkSubnet(network);
    return `${net.serverIp}/${net.prefix}`;
  }));

  let current = [];
  try {
    const out = await exec('ip', ['-4', '-o', 'addr', 'show', 'dev', iface]);
    for (const line of out.split(/\r?\n/)) {
      const match = /\binet\s+(10\.66\.\d{1,3}\.\d{1,3}\/\d{1,2})/.exec(line);
      if (match) current.push(match[1]);
    }
  } catch (error) {
    log.warn?.(`[awg] cannot read addresses: ${error.stderr || error.message}`);
    return { synced: false, reason: 'ip-failed' };
  }

  let added = 0;
  let removed = 0;
  for (const cidr of current) {
    if (!desired.has(cidr)) {
      await exec('ip', ['addr', 'del', cidr, 'dev', iface]).catch(() => {});
      removed += 1;
    }
  }
  for (const cidr of desired) {
    if (!current.includes(cidr)) {
      await exec('ip', ['addr', 'add', cidr, 'dev', iface]).catch((error) => {
        log.warn?.(`[awg] addr add ${cidr}: ${error.stderr || error.message}`);
      });
      added += 1;
    }
  }
  if (added || removed) log.info?.(`[awg] addresses synced: +${added} / -${removed}`);
  return { synced: true, added, removed };
}

/**
 * Networks must not see each other. All peers arrive on one interface, so a
 * single FORWARD chain allows source/destination pairs inside the same /24 and
 * drops everything else that tries to cross between networks.
 */
export async function applyIsolation(cfg, log = console) {
  if (process.platform === 'win32') return { applied: false, reason: 'unsupported-platform' };
  const status = await awgStatus(cfg);
  if (status.dryRun || !status.up) return { applied: false, reason: 'interface-down' };

  const iface = cfg.server.interface;
  try {
    await exec(IPTABLES, ['-N', 'NUROFEN_ISOLATE']).catch(() => {});
    await exec(IPTABLES, ['-F', 'NUROFEN_ISOLATE']);
    for (const network of cfg.networks) {
      const net = networkSubnet(network);
      await exec(IPTABLES, ['-A', 'NUROFEN_ISOLATE', '-s', net.cidr, '-d', net.cidr, '-j', 'RETURN']);
    }
    await exec(IPTABLES, ['-A', 'NUROFEN_ISOLATE', '-j', 'DROP']);
    await exec(IPTABLES, ['-C', 'FORWARD', '-i', iface, '-o', iface, '-j', 'NUROFEN_ISOLATE']).catch(async () => {
      await exec(IPTABLES, ['-I', 'FORWARD', '1', '-i', iface, '-o', iface, '-j', 'NUROFEN_ISOLATE']);
    });
    return { applied: true, networks: cfg.networks.length };
  } catch (error) {
    log.warn?.(`[isolation] failed: ${error.stderr || error.message}`);
    return { applied: false, reason: 'iptables-failed' };
  }
}

/** Adds/removes peers without tearing the interface down (keeps handshakes). */
export async function syncPeers(cfg, log = console) {
  // Keep the on-disk config authoritative: it is what `awg-quick up` will use
  // after a reboot, and what `awg syncconf` style tooling reads.
  const confPath = awgConfFile(cfg);
  fs.mkdirSync(path.dirname(confPath), { recursive: true, mode: 0o700 });
  fs.writeFileSync(confPath, renderServerConfig(cfg), { mode: 0o600 });

  const status = await awgStatus(cfg);
  if (status.dryRun || !status.up) return { synced: false, removed: 0, added: 0 };

  const iface = cfg.server.interface;
  const desired = new Map(
    cfg.peers
      .filter((p) => !p.revoked && isValidKey(p.publicKey))
      .map((p) => [p.publicKey, p.ip]),
  );

  let existing = [];
  try {
    const out = await exec(AWG, ['show', iface, 'peers']);
    existing = out.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
  } catch {
    existing = [];
  }

  let removed = 0;
  for (const pub of existing) {
    if (!desired.has(pub)) {
      await exec(AWG, ['set', iface, 'peer', pub, 'remove']).then(() => {
        removed += 1;
      }).catch(() => {});
    }
  }

  let added = 0;
  let failed = 0;
  for (const [pub, ip] of desired) {
    try {
      await exec(AWG, ['set', iface, 'peer', pub, 'allowed-ips', `${ip}/32`]);
      if (!existing.includes(pub)) added += 1;
    } catch (error) {
      // One bad key must not stop the rest of the network from syncing.
      failed += 1;
      log.warn?.(`[awg] peer ${pub.slice(0, 8)}… skipped: ${error.stderr || error.message}`);
    }
  }

  if (removed || added || failed) {
    log.info?.(`[awg] peers synced: +${added} / -${removed}${failed ? ` / !${failed}` : ''} (total ${desired.size})`);
  }
  return { synced: true, added, removed, failed };
}

/** `awg show <iface> dump` -> per peer handshake and counters. */
export async function dump(cfg) {
  const status = await awgStatus(cfg);
  if (status.dryRun || !status.up) return { available: false, peers: new Map() };
  try {
    const out = await exec(AWG, ['show', cfg.server.interface, 'dump']);
    const lines = out.split(/\r?\n/).filter(Boolean);
    const peers = new Map();
    for (const line of lines.slice(1)) {
      const [publicKey, , endpoint, , latestHandshake, rx, tx] = line.split('\t');
      peers.set(publicKey, {
        endpoint,
        latestHandshake: Number(latestHandshake) * 1000,
        rx: Number(rx),
        tx: Number(tx),
      });
    }
    return { available: true, peers };
  } catch {
    return { available: false, peers: new Map() };
  }
}

export async function down(cfg, log = console) {
  const status = await awgStatus(cfg);
  if (status.dryRun) return false;
  try {
    await exec(AWG_QUICK, ['down', awgConfFile(cfg)]);
    return true;
  } catch (error) {
    log.warn?.(`[awg] down failed: ${error.stderr || error.message}`);
    return false;
  }
}

/**
 * Extra UDP ports that are REDIRECTed to the real AmneziaWG port.
 *
 * A single obfuscation profile behind a single port is easy to blackhole: TSPU
 * adds rules port by port. Giving clients a pool of ports to try (443 looks
 * like QUIC, 500/4500 like IPsec, 51820 like plain WireGuard) means a new
 * filter on one port costs a client one reconnect instead of the whole service.
 */
export async function applyPortPool(cfg, log = console) {
  const ports = [...new Set([cfg.server.awgPort, ...(cfg.server.portPool || [])])]
    .filter((port) => Number.isInteger(port) && port > 0 && port < 65536)
    .filter((port) => port !== cfg.server.awgPort);

  if (process.platform === 'win32') return { applied: false, reason: 'unsupported-platform' };

  try {
    await exec(IPTABLES, ['-t', 'nat', '-N', 'NUROFEN_PORTS']).catch(() => {});
    await exec(IPTABLES, ['-t', 'nat', '-F', 'NUROFEN_PORTS']);
    if (ports.length) {
      await exec(IPTABLES, [
        '-t', 'nat', '-A', 'NUROFEN_PORTS',
        '-p', 'udp', '-m', 'multiport', '--dports', ports.join(','),
        '-j', 'REDIRECT', '--to-ports', String(cfg.server.awgPort),
      ]);
    }
    await exec(IPTABLES, ['-t', 'nat', '-C', 'PREROUTING', '-j', 'NUROFEN_PORTS']).catch(async () => {
      await exec(IPTABLES, ['-t', 'nat', '-I', 'PREROUTING', '1', '-j', 'NUROFEN_PORTS']);
    });
    log.info?.(`[ports] redirect active for udp/${ports.join(',') || '-'} -> ${cfg.server.awgPort}`);
    return { applied: true, ports };
  } catch (error) {
    log.warn?.(`[ports] failed: ${error.stderr || error.message}`);
    return { applied: false, reason: 'iptables-failed' };
  }
}
